const rawDesc = "arbitrary JSON payload, shaped by the event type"

// regression: #5863
func TestRawMessageSchema(t *testing.T) {
	// The same type reached three ways: bare, through a pointer, and as a
	// struct field. Each must take the RawMessage special case on the running
	// toolchain, whatever name reflect gives the type there.
	type holder struct {
		Data json.RawMessage `json:"data"`
	}
	g := &gen{schemas: map[string]any{}}
	raw := reflect.TypeOf(json.RawMessage(nil))

	if got := g.schemaFor(raw); got["description"] != rawDesc {
		t.Errorf("json.RawMessage (reflect name %q in %q) schema = %v, want the RawMessage description",
			raw.Name(), raw.PkgPath(), got)
	}
	if got := g.schemaFor(reflect.TypeOf((*json.RawMessage)(nil))); got["description"] != rawDesc || got["nullable"] != true {
		t.Errorf("*json.RawMessage schema = %v, want the nullable RawMessage description", got)
	}
	field, _ := reflect.TypeOf(holder{}).FieldByName("Data")
	if got := g.schemaRef(field.Type); got["description"] != rawDesc {
		t.Errorf("a json.RawMessage struct field schema = %v, want the RawMessage description", got)
	}
	// A plain []byte is NOT RawMessage: it keeps the base64 string form, so
	// the identity match cannot be satisfied by a check that catches every
	// byte slice.
	if got := g.schemaFor(reflect.TypeOf([]byte(nil))); got["format"] != "byte" {
		t.Errorf("[]byte schema = %v, want type string, format byte", got)
	}
}

// regression: #5863
func TestCommittedSpecCurrent(t *testing.T) {
	// The committed spec must be what this toolchain generates — the in-test
	// form of `go run ./cmd/openapigen -check`.
	want, err := marshal(build())
	if err != nil {
		t.Fatalf("marshal: %v", err)
	}
	have, err := os.ReadFile("../../internal/contract/openapi.yaml")
	if err != nil {
		t.Fatalf("read committed spec: %v", err)
	}
	if !bytes.Equal(have, want) {
		t.Fatal("internal/contract/openapi.yaml differs from the generated bytes — run `go generate ./internal/contract/` and commit")
	}
}
