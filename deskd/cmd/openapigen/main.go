// Command openapigen writes internal/contract/openapi.yaml FROM the typed
// contract (internal/contract), so the OpenAPI document is generated from the
// Go types rather than hand-drifted from them.
//
// The service contract Task 2: the contract package (landed by the v1 contract
// increment 1) is the single home of the wire types; this generator is the
// contract-doc follow-up that package's WireTypes() comment points at. It reads
// contract.Routes for the path table and reflects contract.WireTypes() for the
// component schemas, so a type change that is not reflected in the committed
// openapi.yaml is caught by `go generate ./internal/contract/ && git diff
// --exit-code` (Verify 6).
//
// Usage:
//
//	go run ./cmd/openapigen -out internal/contract/openapi.yaml
//	go run ./cmd/openapigen -check -out internal/contract/openapi.yaml   # drift check
//
// It is deliberately NOT a dependency of the contract package: `go list -deps
// ./internal/contract` (Verify 9, TestLeafImports) does not see it, so the
// generator can import the whole world while the contract stays a leaf.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"reflect"
	"sort"
	"strings"
	"time"

	"gopkg.in/yaml.v3"

	"github.com/medici-finance/assay/deskd/internal/contract"
)

func main() {
	out := flag.String("out", "internal/contract/openapi.yaml", "path to write the OpenAPI document")
	check := flag.Bool("check", false, "do not write; exit 1 if the committed file differs from the generated bytes")
	flag.Parse()

	doc := build()
	got, err := marshal(doc)
	if err != nil {
		fmt.Fprintf(os.Stderr, "openapigen: marshal: %v\n", err)
		os.Exit(2)
	}

	if *check {
		have, err := os.ReadFile(*out)
		if err != nil {
			fmt.Fprintf(os.Stderr, "openapigen: --check could not read %s: %v\n", *out, err)
			os.Exit(2)
		}
		if !bytes.Equal(have, got) {
			fmt.Fprintf(os.Stderr, "openapigen: %s is out of date — run `go generate ./internal/contract/` and commit\n", *out)
			os.Exit(1)
		}
		fmt.Printf("openapigen: %s is up to date\n", *out)
		return
	}

	if err := os.WriteFile(*out, got, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "openapigen: write %s: %v\n", *out, err)
		os.Exit(2)
	}
	fmt.Printf("openapigen: wrote %s (%d routes)\n", *out, len(contract.Routes))
}

// marshal renders the doc with a fixed two-space indent so the output is stable
// across runs (the drift check depends on byte-for-byte stability).
func marshal(doc any) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("# GENERATED by cmd/openapigen from internal/contract — DO NOT EDIT.\n")
	b.WriteString("# Regenerate with `go generate ./internal/contract/`.\n")
	enc := yaml.NewEncoder(&b)
	enc.SetIndent(2)
	if err := enc.Encode(doc); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}

// gen carries the accumulating component-schema set while it walks the wire
// types. Schemas is a plain map so yaml.v3's sorted-key marshalling makes the
// output deterministic without any ordering bookkeeping here.
type gen struct {
	schemas map[string]any
}

func build() map[string]any {
	g := &gen{schemas: map[string]any{}}

	// Register every declared wire type up front, so a type reachable only as a
	// $ref target still gets a component entry.
	for _, v := range contract.WireTypes() {
		g.register(reflect.TypeOf(v))
	}

	paths := map[string]any{}
	for _, r := range contract.Routes {
		p := r.Path
		methods, ok := paths[p].(map[string]any)
		if !ok {
			methods = map[string]any{}
			paths[p] = methods
		}
		methods[strings.ToLower(string(r.Method))] = g.operation(r)
	}

	return map[string]any{
		"openapi": "3.0.3",
		"info": map[string]any{
			"title":   "deskd client↔service contract",
			"version": contract.Version,
			"description": "The typed, versioned HTTP/JSON + SSE wire between the deskd service and its " +
				"client hosts. Generated from the typed routes and wire types in internal/contract. " +
				"MCP is the separate AGENT " +
				"surface and is not described here.",
		},
		"servers": []any{
			map[string]any{"url": "/", "description": "the deskd service (loopback in v1; off-loopback requires the viewer-App validation configured)"},
		},
		"components": map[string]any{
			"securitySchemes": map[string]any{
				"viewerToken": map[string]any{
					"type":        "http",
					"scheme":      "bearer",
					"description": "a read:user-scoped bearer minted by the VIEWER OAuth App, validated against that App; a token from any other App 404s. Reads and identity only; never persisted beyond an in-memory validation cache keyed by token hash (<=120s).",
				},
				"namedActionCredential": map[string]any{
					"type":        "http",
					"scheme":      "bearer",
					"description": "custody rule (b): a per-request, per-named-action write credential the CLIENT supplies on this one request, held in memory for the request only and NEVER stored at rest. The signed-intent body field is the alternative that keeps the raw credential on the client. The service never mints, fetches, or persists a human credential.",
				},
			},
			"schemas": g.schemas,
		},
		"paths": paths,
	}
}

func (g *gen) operation(r contract.Route) map[string]any {
	op := map[string]any{
		"operationId": operationID(r),
		"summary":     r.Summary,
		"x-kind":      string(r.Kind),
	}
	if strings.Contains(r.Path, "{id}") {
		// `{id}` names a DIFFERENT thing per route family, so its description is
		// resolved from the path rather than shared. Getting this wrong is not
		// cosmetic: the description is the only place the document says what a
		// caller may put in the segment, and an escalation id in a /cells/ path
		// is a 400 at best. The escalation id stays the default because it is
		// the shape most routes carry.
		idDesc := "the escalation id (an adapter-minted EscalationID — never the platform issue number)"
		switch {
		case strings.Contains(r.Path, "/desks/"):
			idDesc = "the desk id (<cell>/<role>, as the registry resolves it from cells.yaml — the client never names a target, only a desk)"
		case strings.Contains(r.Path, "/cells/"):
			idDesc = "the cell name, as config/cells.yaml declares it — never a repo slug and never an escalation id"
		case strings.Contains(r.Path, "/sessions/"):
			idDesc = "the custom session id (<cell>/custom/<random>, as POST /v1/sessions returned it) — a configured desk id is refused (403)"
		}
		op["parameters"] = []any{
			map[string]any{
				"name":        "id",
				"in":          "path",
				"required":    true,
				"description": idDesc,
				"schema":      map[string]any{"type": "string"},
			},
		}
	}
	switch r.Kind {
	case contract.KindRead:
		op["security"] = []any{map[string]any{"viewerToken": []any{"read:user"}}}
	case contract.KindEvent:
		op["security"] = []any{map[string]any{"viewerToken": []any{"read:user"}}}
	case contract.KindNamedAction:
		op["x-action"] = string(r.Action)
		op["x-authored-as"] = "the person (custody rule (b))"
		switch r.Action {
		case contract.ActionSend, contract.ActionSession:
			// The terminal actions (the service contract) are NOT GitHub writes:
			// their identity is the per-request VIEWER identity (the viewer
			// bearer off-loopback, the viewer session cookie on loopback), and
			// the answerer write credential is neither required nor accepted.
			op["x-authored-as"] = "the person, on their per-request viewer identity (custody rule (b)); answerer tier on the desk's cell; no GitHub write"
			op["security"] = []any{map[string]any{"viewerToken": []any{"read:user"}}}
		default:
			// EITHER a per-request write credential on the Authorization header
			// OR a signed intent in the body — the two custody-(b) paths.
			op["security"] = []any{map[string]any{"namedActionCredential": []any{}}, map[string]any{}}
		}
	}
	if body := g.requestBody(r); body != nil {
		op["requestBody"] = body
	}
	op["responses"] = g.responses(r)
	return op
}

func (g *gen) requestBody(r contract.Route) map[string]any {
	var schemaName string
	switch {
	case strings.HasSuffix(r.Path, "/answer"):
		schemaName = "AnswerRequest"
	case strings.HasSuffix(r.Path, "/ack"):
		schemaName = "AckRequest"
	case strings.HasSuffix(r.Path, "/terminal/send"):
		schemaName = "SendRequest"
	case r.Method == contract.POST && strings.HasSuffix(r.Path, "/sessions"):
		schemaName = "SessionRequest"
	default:
		return nil
	}
	return map[string]any{
		"required": true,
		"content": map[string]any{
			"application/json": map[string]any{
				"schema": ref(schemaName),
			},
		},
	}
}

func (g *gen) responses(r contract.Route) map[string]any {
	jsonBody := func(schemaName string) map[string]any {
		return map[string]any{
			"content": map[string]any{
				"application/json": map[string]any{"schema": ref(schemaName)},
			},
		}
	}
	switch r.Kind {
	case contract.KindEvent:
		if strings.HasSuffix(r.Path, "/terminal/stream") {
			// The per-desk terminal stream (the service contract) shares the Event
			// envelope with /v1/events but not its id space or its payloads, so
			// it documents its own: the id is a byte cursor, and the data field
			// is one of the two terminal payloads named here.
			return map[string]any{
				"200": map[string]any{
					"description":  "an SSE stream of contract.Event frames (text/event-stream) for ONE desk: `terminal.output` (data: TerminalOutputData — base64 bytes + the cursor at their end), `terminal.state` (data: TerminalStateData) and `resync`. The event id is the desk's scrollback cursor (a cumulative byte offset, decimal); Last-Event-ID resumes strictly after it. A cursor that cannot be honoured (evicted from the ring, or never issued) gets exactly one `resync` whose id is the cursor the stream restarts from — never a silent skip. A `: heartbeat` comment is sent every 15s. Read-only: the route takes no body.",
					"content":      map[string]any{"text/event-stream": map[string]any{"schema": ref("Event")}},
					"x-event-data": []any{ref("TerminalOutputData"), ref("TerminalStateData")},
				},
				"403": map[string]any{"description": "the viewer has no read capability on the desk's cell — refused before any frame"},
				"404": map[string]any{"description": "the id names no configured desk (a configured desk with no target still streams, as could-not-check)"},
				"500": map[string]any{"description": "the response writer on this build cannot stream (no flush support) — refused before any frame, never a buffered pseudo-stream"},
				"503": map[string]any{"description": "the terminal registry is not wired on this build — could-not-check, never a stream that hangs open and delivers nothing"},
			}
		}
		return map[string]any{
			"200": map[string]any{
				"description": "an SSE stream of contract.Event frames (text/event-stream); Last-Event-ID resumes from the ring buffer",
				"content":     map[string]any{"text/event-stream": map[string]any{"schema": ref("Event")}},
			},
		}
	case contract.KindNamedAction:
		switch r.Action {
		case contract.ActionSend:
			resp := jsonBody("SendResult")
			resp["description"] = "the input was written in ONE write once the wait condition held (outcome sent), or this is the recorded receipt of an earlier send with the same request_id (duplicate: true — nothing written by this request)"
			return map[string]any{
				"200": resp,
				"400": map[string]any{"description": "a malformed body (unknown field, bad wait_for/timeout_ms/request_id, missing epoch), or an Authorization header the viewer App does not validate — never tried as a write credential"},
				"401": map[string]any{"description": "no viewer identity accompanied the request"},
				"403": map[string]any{"description": "the viewer is not the answerer on the desk's cell (a commenter may watch, never type), or the authority did not survive the wait — or a cross-origin browser request (a Sec-Fetch-Site other than same-origin/none, or an Origin other than deskd's own), refused before identity is read; nothing written"},
				"404": map[string]any{"description": "the id names no configured desk or open custom session"},
				"409": map[string]any{"description": "nothing written: {error: \"timeout\", state} when the wait expired, or the epoch changed, the desk has no live session, or a send with this request_id is in flight — outcome not-sent"},
				"413": map[string]any{"description": "the input exceeds the per-send bound"},
				"415": map[string]any{"description": "the body is not declared Content-Type: application/json — refused before identity is read, so a CORS simple request can never type into a desk"},
				"429": map[string]any{"description": "too many sends are already pending on this desk"},
				"502": map[string]any{"description": "the write did not report success — outcome-unknown; never replayed by the service (retry with the same request_id to reconcile against the receipt)"},
			}
		case contract.ActionSession:
			if r.Method == contract.DELETE {
				return map[string]any{
					"204": map[string]any{"description": "the custom session was closed and forgotten"},
					"401": map[string]any{"description": "no viewer identity accompanied the request"},
					"403": map[string]any{"description": "{error: \"configured desk\"} for a configured desk id, or the viewer is not the answerer on the session's cell — or a cross-origin browser request (a Sec-Fetch-Site other than same-origin/none, or an Origin other than deskd's own), refused before identity is read"},
					"404": map[string]any{"description": "no such custom session"},
				}
			}
			resp := jsonBody("SessionRow")
			resp["description"] = "the custom session opened on the configured desk's own target (memory-only; a restart forgets it)"
			return map[string]any{
				"201": resp,
				"400": map[string]any{"description": "a malformed body — any field the contract does not declare (a container, pod or command among them) is refused; the client never names a target"},
				"401": map[string]any{"description": "no viewer identity accompanied the request"},
				"403": map[string]any{"description": "the viewer is not the answerer on the desk's cell — or a cross-origin browser request (a Sec-Fetch-Site other than same-origin/none, or an Origin other than deskd's own), refused before identity is read"},
				"404": map[string]any{"description": "on names no configured desk"},
				"415": map[string]any{"description": "the body is not declared Content-Type: application/json — refused before identity is read, so a CORS simple request can never open a session"},
				"429": map[string]any{"description": "too many custom sessions are open on this cell"},
				"501": map[string]any{"description": "a skill session is could-not-check on a build that carries no bundled plugin manifest"},
				"503": map[string]any{"description": "the desk has no attachable target, no driver for its kind is linked, or the target is unreachable — could-not-check; or the desk is a pod desk, which deskd holds no cluster access grant for — {error: …unauthorized…}, refused before any driver is built"},
			}
		}
		resp := jsonBody("ActionResult")
		resp["description"] = "the named action was performed; the result records what was authored and as whom"
		return map[string]any{"200": resp}
	case contract.KindLocalState:
		// The cell-override POST is the one local-state route that ANSWERS with
		// the state it just wrote: serve.Overrides.handlePost returns 200 and the
		// merged OverridesResponse (the table after the merge, plus record_pr),
		// because the caller needs to see what the partial body merged INTO and
		// whether the record PR was filed. The default stays 204/no-body, which is
		// what /escalations/{id}/read documents and what serve.handleV1Read
		// answers since the service contract increment 4 mounted it.
		if strings.HasSuffix(r.Path, "/cells/{id}/overrides") {
			resp := jsonBody("OverridesResponse")
			resp["description"] = "the cell's override table AFTER the merge, with record_pr naming the record PR's status (could-not-check when the write-issues App is unconfigured)"
			return map[string]any{"200": resp}
		}
		return map[string]any{"204": map[string]any{"description": "service-local state recorded; no platform write and no body"}}
	case contract.KindNudge:
		return map[string]any{"202": map[string]any{"description": "the re-fetch was requested (App-identity read, idempotent); no human write occurs"}}
	default: // read
		var schemaName string
		switch {
		case strings.HasSuffix(r.Path, "/inbox"):
			schemaName = "InboxResponse"
		case strings.HasSuffix(r.Path, "/escalations/{id}"):
			schemaName = "EscalationResponse"
		case strings.HasSuffix(r.Path, "/desks/{id}/terminal"):
			schemaName = "TerminalHandle"
		case strings.HasSuffix(r.Path, "/cells/{id}/overrides"):
			schemaName = "OverridesResponse"
		case strings.HasSuffix(r.Path, "/desks"):
			schemaName = "DesksResponse"
		}
		if schemaName == "" {
			return map[string]any{
				"200": map[string]any{
					"description": r.Summary + " (envelope carries the staleness meta; see internal/serve for the payload shape)",
				},
			}
		}
		resp := jsonBody(schemaName)
		resp["description"] = r.Summary
		if strings.HasSuffix(r.Path, "/desks/{id}/terminal") {
			// The handle read is gated per cell exactly as the stream is.
			return map[string]any{
				"200": resp,
				"403": map[string]any{"description": "the viewer has no read capability on the desk's cell — decided from the cell, before the desk is looked up"},
				"404": map[string]any{"description": "the id names no configured desk (a configured desk with no target is a could-not-check 200, not a 404)"},
			}
		}
		return map[string]any{"200": resp}
	}
}

// register adds t's component schema (and every contract struct it reaches) to
// g.schemas, keyed by the Go type name. Idempotent.
func (g *gen) register(t reflect.Type) {
	t = deref(t)
	if !isContractStruct(t) {
		return
	}
	if _, done := g.schemas[t.Name()]; done {
		return
	}
	// Reserve the name before recursing so a self-reference terminates.
	g.schemas[t.Name()] = map[string]any{}
	g.schemas[t.Name()] = g.structSchema(t)
}

func (g *gen) structSchema(t reflect.Type) map[string]any {
	props := map[string]any{}
	var required []string
	g.collectFields(t, props, &required)
	s := map[string]any{"type": "object", "properties": props}
	if len(required) > 0 {
		sort.Strings(required)
		s["required"] = toAnySlice(required)
	}
	return s
}

func (g *gen) collectFields(t reflect.Type, props map[string]any, required *[]string) {
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		if f.PkgPath != "" { // unexported
			continue
		}
		parts := strings.Split(f.Tag.Get("json"), ",")
		name := parts[0]
		opts := parts[1:]
		if f.Anonymous && name == "" {
			ft := deref(f.Type)
			if ft.Kind() == reflect.Struct {
				g.collectFields(ft, props, required)
				continue
			}
		}
		if name == "-" {
			continue
		}
		if name == "" {
			name = f.Name
		}
		props[name] = g.schemaRef(f.Type)
		if !contains(opts, "omitempty") {
			*required = append(*required, name)
		}
	}
}

// schemaRef returns a $ref for a contract struct (registering it) or an inline
// schema for everything else. A slice/array whose ELEMENT is a contract
// struct is special-cased FIRST into {type: array, items: <$ref>} — otherwise
// a []ContractStruct field (e.g. DesksResponse.Desks []DeskRow,
// the service contract) would deref straight past the slice to its element and
// render as a bare $ref instead of an array, which a generated client would
// decode as one object rather than a list. Every other slice (a plain
// []byte/json.RawMessage, or a slice of a domain/primitive type) still goes
// through [gen.schemaFor], unchanged — that is where the json.RawMessage and
// raw-[]byte special cases already live, so this must delegate to it rather
// than duplicate them.
func (g *gen) schemaRef(t reflect.Type) map[string]any {
	if t.Kind() == reflect.Slice || t.Kind() == reflect.Array {
		if isContractStruct(deref(t.Elem())) {
			return map[string]any{"type": "array", "items": g.schemaRef(t.Elem())}
		}
		return g.schemaFor(t)
	}
	dt := deref(t)
	if isContractStruct(dt) {
		g.register(dt)
		return ref(dt.Name())
	}
	return g.schemaFor(t)
}

func (g *gen) schemaFor(t reflect.Type) map[string]any {
	if t.Kind() == reflect.Ptr {
		s := g.schemaFor(t.Elem())
		s["nullable"] = true
		return s
	}
	if t == reflect.TypeOf(time.Time{}) {
		return map[string]any{"type": "string", "format": "date-time"}
	}
	if t.PkgPath() == "encoding/json" && t.Name() == "RawMessage" {
		return map[string]any{"description": "arbitrary JSON payload, shaped by the event type"}
	}
	switch t.Kind() {
	case reflect.String:
		return map[string]any{"type": "string"}
	case reflect.Bool:
		return map[string]any{"type": "boolean"}
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		return map[string]any{"type": "integer"}
	case reflect.Float32, reflect.Float64:
		return map[string]any{"type": "number"}
	case reflect.Slice, reflect.Array:
		if t.Elem().Kind() == reflect.Uint8 {
			// []byte marshals to a base64 string (e.g. an ed25519 signature — a
			// signature over a record, not a credential).
			return map[string]any{"type": "string", "format": "byte"}
		}
		return map[string]any{"type": "array", "items": g.schemaRef(t.Elem())}
	case reflect.Map:
		return map[string]any{"type": "object", "additionalProperties": g.schemaRef(t.Elem())}
	case reflect.Struct:
		if strings.Contains(t.PkgPath(), "/internal/domain") {
			return map[string]any{"type": "object", "description": "domain." + t.Name() + " — a platform-clean domain type; see internal/domain"}
		}
		return g.structSchema(t)
	default:
		return map[string]any{}
	}
}

func operationID(r contract.Route) string {
	p := strings.NewReplacer(contract.Prefix+"/", "", "/", "_", "{", "", "}", "").Replace(r.Path)
	return strings.ToLower(string(r.Method)) + "_" + p
}

func ref(name string) map[string]any {
	return map[string]any{"$ref": "#/components/schemas/" + name}
}

func isContractStruct(t reflect.Type) bool {
	return t.Kind() == reflect.Struct &&
		t != reflect.TypeOf(time.Time{}) &&
		strings.HasSuffix(t.PkgPath(), "/internal/contract")
}

func deref(t reflect.Type) reflect.Type {
	for t.Kind() == reflect.Ptr || t.Kind() == reflect.Slice || t.Kind() == reflect.Array {
		t = t.Elem()
	}
	return t
}

func contains(ss []string, want string) bool {
	for _, s := range ss {
		if s == want {
			return true
		}
	}
	return false
}

func toAnySlice(ss []string) []any {
	out := make([]any, len(ss))
	for i, s := range ss {
		out[i] = s
	}
	return out
}
