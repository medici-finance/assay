package main

// readmemilestones.go — the generated milestone region of a stream README
// (milestone-support/11).
//
// OWNER. statusgen owns this region exactly as it owns the Briefs table: the
// content between the milestone markers is a pure function of the stream's
// loaded MilestonePlan and is rewritten by `regen --readmes` and checked by
// `--lint`. The region is separate from the Briefs region (its own markers), so
// the Briefs table's column ownership, preserved lifecycle cells and authored
// prose are untouched.
//
// WHAT IT HOLDS. Plan facts only: coverage, each milestone's supported scope,
// prerequisites and evidence paths, and the reverse membership index. Live
// state (work remaining, acceptance, availability, holds) depends on a
// readiness evaluation that `regen` does not run, so it is NOT committed here: a
// committed copy would be a manually maintained status that goes stale. The
// versioned stream view and `deskboard milestones` project it instead.
//
// OPT-IN. A README opts in by carrying the markers; a stream that has not
// opted in to milestone-v1 must not carry them (no fake milestones for fixture
// or outline streams), and a stream without markers is left byte-identical.

import (
	"fmt"
	"os"
	"sort"
	"strings"
)

const (
	milestonesMarkerBegin = "<!-- statusgen:milestones:begin -->"
	milestonesMarkerEnd   = "<!-- statusgen:milestones:end -->"
)

// extractMilestoneRegion locates the milestone region. present reports whether
// either marker appears; ok that both do, in order. A begin marker inside the
// Briefs region is a malformed layout and reported as not ok.
func extractMilestoneRegion(content string) (prefix, region, suffix string, present, ok bool) {
	bi := strings.Index(content, milestonesMarkerBegin)
	ei := strings.Index(content, milestonesMarkerEnd)
	present = bi >= 0 || ei >= 0
	if bi < 0 || ei < bi+len(milestonesMarkerBegin) || strings.Count(content, milestonesMarkerBegin) != 1 || strings.Count(content, milestonesMarkerEnd) != 1 {
		return "", "", "", present, false
	}
	if b0 := strings.Index(content, briefsMarkerBegin); b0 >= 0 {
		if b1 := strings.Index(content, briefsMarkerEnd); b1 > b0 && bi > b0 && bi < b1 {
			return "", "", "", present, false
		}
	}
	return content[:bi+len(milestonesMarkerBegin)], content[bi+len(milestonesMarkerBegin) : ei], content[ei:], present, true
}

// mdCell makes untrusted record text safe inside one table cell.
func mdCell(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	if s == "" {
		return emptyCell
	}
	return escapeTableCell(s)
}

func mdCode(s string) string {
	if s == "" || strings.ContainsAny(s, "`\n\r") {
		return mdCell(s)
	}
	return "`" + escapeTableCell(s) + "`"
}

func joinCells(items []string) string {
	if len(items) == 0 {
		return emptyCell
	}
	out := make([]string, len(items))
	for i, it := range items {
		out[i] = mdCode(it)
	}
	return strings.Join(out, "<br>")
}

// renderMilestoneRegion renders the region for one opted-in stream. It reads
// only the plan, so equal plans render equal bytes.
func renderMilestoneRegion(s *Stream) string {
	p := s.Milestones
	var b strings.Builder
	b.WriteString("_Generated by `statusgen regen --readmes` from `milestones/`. Do not edit. Work remaining, acceptance and availability are not recorded here; read them from the stream view or `deskboard milestones`._\n\n")
	var gaps []string
	for _, d := range p.Diagnostics {
		gaps = append(gaps, fmt.Sprintf("refused %s: %s", d.Path, d.Reason))
	}
	for _, u := range p.Unknowns {
		gaps = append(gaps, fmt.Sprintf("unknown %s: %s", u.Path, u.Reason))
	}
	sort.Strings(gaps)
	if len(gaps) == 0 && p.Coverage == MilestoneCoverageKnown {
		fmt.Fprintf(&b, "Coverage: known (%d milestone records).\n", len(p.Records))
	} else {
		fmt.Fprintf(&b, "Coverage: unknown (%d milestone records read, %d gaps). Nothing below is a complete list.\n", len(p.Records), len(gaps))
		for _, g := range gaps {
			b.WriteString("\n- " + strings.Join(strings.Fields(g), " "))
		}
		b.WriteString("\n")
	}
	if len(p.Records) == 0 {
		return strings.TrimRight(b.String(), "\n")
	}
	b.WriteString("\n| Milestone | Title | Supported scope | Prerequisites | Evidence |\n|---|---|---|---|---|\n")
	byBrief := map[string][]string{}
	for _, r := range p.Records {
		var scope, prereq, evidence []string
		for _, c := range r.Contributes {
			scope = append(scope, c.LogicalKey)
			byBrief[c.LogicalKey] = append(byBrief[c.LogicalKey], r.Ref())
		}
		for _, q := range r.RequiresMilestones {
			prereq = append(prereq, fmt.Sprintf("%s@%d", q.Identity.String(), q.Revision))
		}
		seen := map[string]bool{}
		for _, c := range r.Criteria {
			for _, e := range c.Evidence {
				if !seen[e] {
					seen[e] = true
					evidence = append(evidence, e)
				}
			}
		}
		sort.Strings(evidence)
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s |\n", mdCode(r.Ref()), mdCell(r.Title), joinCells(scope), joinCells(prereq), joinCells(evidence))
	}
	briefs := make([]string, 0, len(byBrief))
	for k := range byBrief {
		briefs = append(briefs, k)
	}
	sort.Strings(briefs)
	if len(briefs) > 0 {
		b.WriteString("\nMembership (brief to the milestones that list it):\n\n| Brief | Milestones |\n|---|---|\n")
		for _, k := range briefs {
			refs := byBrief[k]
			sort.Strings(refs)
			fmt.Fprintf(&b, "| %s | %s |\n", mdCode(k), joinCells(refs))
		}
	}
	return strings.TrimRight(b.String(), "\n")
}

// rewriteMilestoneRegion regenerates the milestone region in place. A README
// without the markers is left alone; markers on a stream that has not opted in
// are an error.
func rewriteMilestoneRegion(s *Stream, path string) (changed bool, err error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return false, err
	}
	content := string(raw)
	prefix, _, suffix, present, ok := extractMilestoneRegion(content)
	if !present {
		return false, nil
	}
	if !ok {
		return false, fmt.Errorf("%s: malformed milestone region: need exactly one %s then one %s, outside the Briefs region", path, milestonesMarkerBegin, milestonesMarkerEnd)
	}
	if s.Milestones == nil || !s.Milestones.OptedIn {
		return false, fmt.Errorf("%s: milestone region present but the stream has not opted in to milestone-v1 through reader-requirements; remove the markers rather than generate fake milestones", path)
	}
	next := framedRegion(prefix, renderMilestoneRegion(s), suffix)
	if next == content {
		return false, nil
	}
	return true, os.WriteFile(path, []byte(next), 0o644)
}

// checkMilestoneRegions is the --lint arm: a hand edit to the region, a
// malformed region, or markers on a stream that did not opt in are PROBLEMs.
// Offline and tree-only; it never writes.
func checkMilestoneRegions(streams []*Stream) (problems []string) {
	for _, s := range streams {
		path := s.Dir + "/README.md"
		raw, err := os.ReadFile(path)
		if err != nil {
			continue // the Briefs check and the parser already report unreadable READMEs
		}
		_, region, _, present, ok := extractMilestoneRegion(string(raw))
		switch {
		case !present:
		case !ok:
			problems = append(problems, fmt.Sprintf("%s README: malformed milestone region — need exactly one %s then one %s, outside the Briefs region", s.Name, milestonesMarkerBegin, milestonesMarkerEnd))
		case s.Milestones == nil || !s.Milestones.OptedIn:
			problems = append(problems, fmt.Sprintf("%s README: milestone region on a stream that has not opted in to milestone-v1 — remove the markers; a legacy or outline stream gets no milestones", s.Name))
		case strings.TrimSpace(region) != strings.TrimSpace(renderMilestoneRegion(s)):
			problems = append(problems, fmt.Sprintf("%s README: hand edit to a generated milestone region — it differs from a fresh render of milestones/; regenerate with `statusgen regen --readmes`", s.Name))
		}
	}
	return problems
}
