// cliHelpForms is every help, version and kits spelling across the modes.
func cliHelpForms() [][]string {
	forms := [][]string{{"-h"}, {"--help"}, {"help"}, {"-help"}, {"--version"}, {"-version"}, {"--kits"}, {"--trace", "--kits"}, {"--kits", "--trace"}}
	for _, mode := range []string{"--stamp-only", "--check-verifier", "--attest-verifier"} {
		forms = append(forms, clicontract.HelpForms(mode)...)
		forms = append(forms, clicontract.GoFlagHelpForms(mode)...)
		forms = append(forms, []string{mode, "--version"}, []string{mode, "-version"})
	}
	return append(forms, []string{"issue-1", "--help"}, []string{"--trace", "--help"})
}

func cliBuildBinary(t *testing.T) string {
	t.Helper()
	bin := filepath.Join(t.TempDir(), "deskdispatch")
	if runtime.GOOS == "windows" {
		bin += ".exe"
	}
	if out, err := exec.Command("go", "build", "-o", bin, ".").CombinedOutput(); err != nil {
		t.Fatalf("build: %v\n%s", err, out)
	}
	return bin
}

// cliHome is a fresh home whose roster.env holds one malformed configuration, plus a
// PATH directory of shims that record any child process the binary starts.
func cliHome(t *testing.T, content string, write bool) string {
	t.Helper()
	home := t.TempDir()
	dir := filepath.Join(home, ".config", "assay")
	if err := os.MkdirAll(dir, 0o700); err != nil {
		t.Fatal(err)
	}
	if write {
		if err := os.WriteFile(filepath.Join(dir, "roster.env"), []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return home
}

// cliChildEnv is a hermetic environment: malformed values everywhere a loader would
// look, the kill switch armed, and a PATH whose every tool records its own start.
func cliChildEnv(home, consent string) []string {
	env := []string{"HOME=" + home, "USERPROFILE=" + home, "PATH=" + filepath.Join(filepath.Dir(home), "shims"), "KUBECONFIG=/dev/null", "DESK_TOOLS_DISABLED=1", "ASSAY_CONFIG_ECHO=full", "DESK_MIN_FREE_BYTES=invalid", "CELL_GO_CACHE_ROOT=" + filepath.Join(home, "unreadable-cache"), "CLI_SHIM_MARK=" + filepath.Join(filepath.Dir(home), "child-started")}
	if consent != "" {
		env = append(env, "ASSAY_TELEMETRY="+consent)
	}
	return env
}

// cliRunHelp runs one help/version form from dir and requires zero effects: no stderr,
// no child process, no state written — except, under explicit telemetry consent, the
// one local perf record whose verb classifies args[0] without reading configuration.
func cliRunHelp(t *testing.T, bin, home, dir string, args []string, consent string) {
	t.Helper()
	shims := filepath.Join(filepath.Dir(home), "shims")
	if err := os.MkdirAll(shims, 0o755); err != nil {
		t.Fatal(err)
	}
	if runtime.GOOS != "windows" {
		for _, name := range []string{"git", "gh", "go", "deskclaim-ref", "desktoken", "kubectl", "ssh", "bash"} {
			shim := "#!/bin/sh\necho \"$0\" >> \"$CLI_SHIM_MARK\"\nexit 1\n"
			if err := os.WriteFile(filepath.Join(shims, name), []byte(shim), 0o755); err != nil {
				t.Fatal(err)
			}
		}
	}
	mark := filepath.Join(filepath.Dir(home), "child-started")
	ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
	defer cancel()
	cmd := exec.CommandContext(ctx, bin, args...)
	cmd.Dir, cmd.Env = dir, cliChildEnv(home, consent)
	before := cliHomeStamp(t, home)
	var out, errs bytes.Buffer
	cmd.Stdout, cmd.Stderr = &out, &errs
	if err := cmd.Run(); err != nil {
		t.Fatalf("help/version %v consent=%q: %v\n%s\n%s", args, consent, err, &out, &errs)
	}
	if out.Len() == 0 {
		t.Errorf("missing generated help/version output: %v", args)
	}
	if errs.Len() != 0 {
		t.Errorf("help %v read config or ran activation: %s", args, &errs)
	}
	if started, err := os.ReadFile(mark); err == nil {
		t.Errorf("help %v started a child process: %s", args, started)
	}
	after := cliHomeStamp(t, home)
	perf := filepath.Join(".config", "assay", "perf")
	var records []string
	perfEntries := 0
	for path, data := range after {
		if path == perf || strings.HasPrefix(path, perf+string(filepath.Separator)) {
			perfEntries++
			if strings.HasSuffix(path, ".jsonl") {
				records = append(records, strings.Split(strings.TrimSpace(data), "\n")...)
			}
			delete(after, path)
		}
	}
	if !reflect.DeepEqual(before, after) {
		t.Errorf("help/version %v consent=%q wrote configuration, lock or cache state", args, consent)
	}
	if consent == "" {
		if perfEntries != 0 {
			t.Errorf("help/version %v wrote telemetry without consent", args)
		}
		return
	}
	want := "other"
	for _, v := range perfVerbs {
		if v == args[0] {
			want = v
		}
	}
	if len(records) != 1 {
		t.Fatalf("consented help %v: %d perf records, want exactly one", args, len(records))
	}
	var rec struct {
		Schema, Tool, Verb string
		Exit               int
		Counters           map[string]int64
		Unavailable        []string
	}
	if err := json.Unmarshal([]byte(records[0]), &rec); err != nil {
		t.Fatal(err)
	}
	if rec.Schema != "perf-v2" || rec.Tool != "deskdispatch" || rec.Verb != want || rec.Exit != 0 {
		t.Errorf("consented help %v record = %+v, want perf-v2 verb %q exit 0", args, rec, want)
	}
	// perf-v2 carries the child-process and forge-call counts in counters. A key that is
	// absent or listed unavailable was not measured, so it must fail rather than read as 0.
	for _, key := range []string{"subprocess", "http"} {
		n, ok := rec.Counters[key]
		if !ok || n != 0 || slices.Contains(rec.Unavailable, key) {
			t.Errorf("consented help %v counter %q = %d present=%v unavailable=%v, want measured zero", args, key, n, ok, rec.Unavailable)
		}
	}
}

// cliManifestTree is a checkout with a large component.yaml population, malformed
// manifests, and a desk-verbs owner whose required key nothing provides (inactive):
// any activation discovery from this tree prints a refusal and exits unverifiable.
func cliManifestTree(t *testing.T) string {
	t.Helper()
	tree := t.TempDir()
	write := func(rel, body string) {
		path := filepath.Join(tree, rel)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write(".git/HEAD", "ref: refs/heads/main\n")
	write("verbs/component.yaml", "component: test/desk-verbs\nversion: 0.0.1\nprovides:\n  - assay.desk.verbs\ninject:\n  required:\n    - key: test.never.provided\n  optional: []\n")
	for i := 0; i < 600; i++ {
		write(fmt.Sprintf("c/%02d/m%03d/component.yaml", i/40, i), fmt.Sprintf("component: test/bulk-%03d\nversion: 0.0.1\nprovides:\n  - test.bulk.%03d\ninject:\n  required: []\n  optional: []\n", i, i))
	}
	write("broken/a/component.yaml", "component: [unterminated\n\x00")
	write("broken/b/component.yaml", "version: 0.0.1\n")
	return tree
}

