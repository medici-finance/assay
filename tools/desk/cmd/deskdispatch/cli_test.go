func TestCLIConfigFlow(t *testing.T) {
	for _, mode := range []string{"", "--stamp-only", "--check-verifier", "--attest-verifier"} {
		for _, binding := range dispatchBindings(mode) {
			if binding.Key == "trace" || binding.Key == "kits" {
				continue
			}
			t.Run(mode+"/"+binding.Key, func(t *testing.T) {
				for _, row := range clicontract.Precedence {
					// No CLI binding has an env or config source. The all-source fixture is
					// applied to an undeclared key; it cannot widen any declared flag.
					args := []string{}
					if mode != "" {
						args = append(args, mode)
					} else {
						args = append(args, "issue-7")
					}
					cfg := map[string]any{"unrelated": "ignored"}
					if row.Config != nil {
						cfg["unrelated"] = *row.Config
					}
					lookups := 0
					env := dispatchCLI{inputs: cli.Inputs{Config: cfg, LookupEnv: func(string) (string, bool) {
						lookups++
						if row.Env != nil {
							return *row.Env, true
						}
						return "", false
					}}}
					want := cliDefault(mode, binding.Key)
					if !reflect.DeepEqual(binding.Default, want) {
						t.Fatalf("declaration default for %s = %#v, baseline %#v", binding.Key, binding.Default, want)
					}
					if row.Flag != nil {
						val := *row.Flag
						switch binding.Kind {
						case cli.Bool:
							val = "true"
							want = true
						case cli.Int:
							val = "17"
							want = 17
						default:
							want = val
						}
						args = append(args, "--"+binding.Flag+"="+val)
					}
					called := 0
					env.handle = func(gotMode string, o dispatchOpts, override string) error {
						called++
						if gotMode != mode {
							t.Errorf("mode=%q", gotMode)
						}
						got := cliFields(o, override)[binding.Key]
						if !reflect.DeepEqual(got, want) {
							t.Errorf("%s: %s got %#v want %#v", row.Name, binding.Key, got, want)
						}
						return nil
					}
					var out bytes.Buffer
					if code := parseDispatchCLI(args, env, cli.IO{Out: &out, Err: &out}); code != 0 {
						t.Fatalf("%s code=%d: %s", row.Name, code, &out)
					}
					if called != 1 || lookups != 0 {
						t.Fatalf("handoffs=%d undeclared env reads=%d", called, lookups)
					}
				}
				// A known CLI key is not silently admitted from a config file either.
				called := false
				env := dispatchCLI{inputs: cli.Inputs{Config: map[string]any{binding.Key: binding.Default}}, handle: func(string, dispatchOpts, string) error { called = true; return nil }}
				args := []string{"issue-7"}
				if mode != "" {
					args = []string{mode}
				}
				var out bytes.Buffer
				if code := parseDispatchCLI(args, env, cli.IO{Out: &out, Err: &out}); code != 5 || called {
					t.Fatalf("config binding widened: code=%d called=%v %s", code, called, &out)
				}
			})
		}
	}
}

