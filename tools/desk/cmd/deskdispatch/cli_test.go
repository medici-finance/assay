// regression: #2111
func TestCLIHelpOffline(t *testing.T) {
	bin := filepath.Join(t.TempDir(), "deskdispatch")
	if runtime.GOOS == "windows" {
		bin += ".exe"
	}
	build := exec.Command("go", "build", "-o", bin, ".")
	if out, err := build.CombinedOutput(); err != nil {
		t.Fatalf("build: %v\n%s", err, out)
	}
	modes := []string{"--stamp-only", "--check-verifier", "--attest-verifier"}
	forms := [][]string{{"-h"}, {"--help"}, {"help"}, {"-help"}, {"--version"}, {"-version"}, {"--kits"}, {"--trace", "--kits"}, {"--kits", "--trace"}}
	for _, mode := range modes {
		forms = append(forms, clicontract.HelpForms(mode)...)
		forms = append(forms, clicontract.GoFlagHelpForms(mode)...)
		forms = append(forms, []string{mode, "--version"}, []string{mode, "-version"})
	}
	forms = append(forms, []string{"issue-1", "--help"}, []string{"--trace", "--help"})
	for _, cfg := range clicontract.MalformedConfigs {
		t.Run(cfg.Name, func(t *testing.T) {
			home := t.TempDir()
			dir := filepath.Join(home, ".config", "assay")
			if err := os.MkdirAll(dir, 0700); err != nil {
				t.Fatal(err)
			}
			if cfg.Name != "absent" {
				if err := os.WriteFile(filepath.Join(dir, "roster.env"), []byte(cfg.Content), 0600); err != nil {
					t.Fatal(err)
				}
			}
			for _, args := range forms {
				t.Run(strings.Join(args, "_"), func(t *testing.T) {
					reads, effects := 0, 0
					var generated bytes.Buffer
					env := dispatchCLI{inputs: cli.Inputs{LookupEnv: func(string) (string, bool) { reads++; return "", false }}, before: func() error { reads++; return nil }, handle: func(string, dispatchOpts, string) error { effects++; return nil }}
					if code := parseDispatchCLI(args, env, cli.IO{Out: &generated, Err: &generated}); code != 0 || reads != 0 || effects != 0 {
						t.Fatalf("help path code=%d reads=%d effects=%d: %s", code, reads, effects, &generated)
					}
					ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
					defer cancel()
					cmd := exec.CommandContext(ctx, bin, args...)
					cmd.Env = []string{"HOME=" + home, "USERPROFILE=" + home, "PATH=" + t.TempDir(), "KUBECONFIG=/dev/null", "DESK_TOOLS_DISABLED=1", "ASSAY_CONFIG_ECHO=full", "ASSAY_TELEMETRY=1", "DESK_MIN_FREE_BYTES=invalid", "CELL_GO_CACHE_ROOT=" + filepath.Join(home, "unreadable-cache")}
					var out, errs bytes.Buffer
					cmd.Stdout = &out
					cmd.Stderr = &errs
					if err := cmd.Run(); err != nil {
						t.Fatalf("help/version %v: %v\n%s\n%s", args, err, &out, &errs)
					}
					if out.Len() == 0 {
						t.Errorf("missing generated help/version output: %v", args)
					}
					if errs.Len() != 0 {
						t.Errorf("help read config or ran activation: %s", &errs)
					}
				})
			}
		})
	}
}

// regression: #2111
func TestCLIConfigFlow(t *testing.T) {
	for _, mode := range []string{"", "--stamp-only", "--check-verifier", "--attest-verifier"} {
		for _, binding := range dispatchBindings(mode) {
			if binding.Key == "trace" || binding.Key == "kits" {
				continue
			}
			t.Run(mode+"/"+binding.Key, func(t *testing.T) {
				for _, row := range clicontract.Precedence {
					// No CLI binding has an env or config source. The all-source fixture is
					// applied to an undeclared key; it cannot widen any declared flag.
					args := []string{}
					if mode != "" {
						args = append(args, mode)
					} else {
						args = append(args, "issue-7")
					}
					cfg := map[string]any{"unrelated": "ignored"}
					if row.Config != nil {
						cfg["unrelated"] = *row.Config
					}
					lookups := 0
					env := dispatchCLI{inputs: cli.Inputs{Config: cfg, LookupEnv: func(string) (string, bool) {
						lookups++
						if row.Env != nil {
							return *row.Env, true
						}
						return "", false
					}}}
					want := cliDefault(mode, binding.Key)
					if !reflect.DeepEqual(binding.Default, want) {
						t.Fatalf("declaration default for %s = %#v, baseline %#v", binding.Key, binding.Default, want)
					}
					if row.Flag != nil {
						val := *row.Flag
						switch binding.Kind {
						case cli.Bool:
							val = "true"
							want = true
						case cli.Int:
							val = "17"
							want = 17
						default:
							want = val
						}
						args = append(args, "--"+binding.Flag+"="+val)
					}
					called := 0
					env.handle = func(gotMode string, o dispatchOpts, override string) error {
						called++
						if gotMode != mode {
							t.Errorf("mode=%q", gotMode)
						}
						got := cliFields(o, override)[binding.Key]
						if !reflect.DeepEqual(got, want) {
							t.Errorf("%s: %s got %#v want %#v", row.Name, binding.Key, got, want)
						}
						return nil
					}
					var out bytes.Buffer
					if code := parseDispatchCLI(args, env, cli.IO{Out: &out, Err: &out}); code != 0 {
						t.Fatalf("%s code=%d: %s", row.Name, code, &out)
					}
					if called != 1 || lookups != 0 {
						t.Fatalf("handoffs=%d undeclared env reads=%d", called, lookups)
					}
				}
				// A known CLI key is not silently admitted from a config file either.
				called := false
				env := dispatchCLI{inputs: cli.Inputs{Config: map[string]any{binding.Key: binding.Default}}, handle: func(string, dispatchOpts, string) error { called = true; return nil }}
				args := []string{"issue-7"}
				if mode != "" {
					args = []string{mode}
				}
				var out bytes.Buffer
				if code := parseDispatchCLI(args, env, cli.IO{Out: &out, Err: &out}); code != 5 || called {
					t.Fatalf("config binding widened: code=%d called=%v %s", code, called, &out)
				}
			})
		}
	}
}

func cliFields(o dispatchOpts, override string) map[string]any {
	return map[string]any{"tier": o.tier, "kit": o.kit, "repo": o.repo, "root": o.root, "claim-root": o.claimRoot, "model": o.model, "branch": o.branch, "brief": o.brief, "gate-human": o.gateHuman, "pr": o.pr, "prompt-file": o.promptFile, "quiet": o.quiet, "dry-run": o.dryRun, "worktree": o.worktree, "rework": o.rework, "attest-worker": o.attestWorker, "cross-repo": o.crossRepo, "attestation": o.attestation, "force-scan-override": override}
}

// regression: #2111
func TestCLILegacyForms(t *testing.T) {
	for _, mode := range []string{"", "--stamp-only", "--check-verifier", "--attest-verifier"} {
		for _, binding := range dispatchBindings(mode) {
			if binding.Kind != cli.String {
				continue
			}
			for _, path := range clicontract.PathValues {
				for _, form := range clicontract.OptionForms {
					t.Run(mode+"/"+binding.Key+"/"+path.Name+"/"+form.Name, func(t *testing.T) {
						args := []string{"issue-7"}
						if mode != "" {
							args = []string{mode}
						}
						args = append(args, form.Args(binding.Flag, path.Value)...)
						called := 0
						env := dispatchCLI{handle: func(gotMode string, o dispatchOpts, override string) error {
							called++
							if gotMode != mode || cliFields(o, override)[binding.Key] != path.Value {
								t.Errorf("value changed for %s: mode %q fields %v", binding.Key, gotMode, cliFields(o, override))
							}
							return nil
						}}
						var out bytes.Buffer
						if code := parseDispatchCLI(args, env, cli.IO{Out: &out, Err: &out}); code != 0 || called != 1 {
							t.Fatalf("code=%d calls=%d: %s", code, called, &out)
						}
					})
				}
			}
		}
	}
	for _, mode := range []string{"", "--stamp-only", "--check-verifier", "--attest-verifier"} {
		for _, binding := range dispatchBindings(mode) {
			if binding.Key == "trace" || binding.Key == "kits" {
				continue
			}
			first, last := "first", "last"
			var want any = last
			switch binding.Kind {
			case cli.Bool:
				first, last = "true", "false"
				want = false
			case cli.Int:
				first, last = "3", "7"
				want = 7
			}
			args := []string{"issue-7"}
			if mode != "" {
				args = []string{mode}
			}
			args = append(args, "--"+binding.Flag+"="+first, "-"+binding.Flag+"="+last)
			var out bytes.Buffer
			calls := 0
			env := dispatchCLI{handle: func(_ string, o dispatchOpts, override string) error {
				calls++
				if got := cliFields(o, override)[binding.Key]; !reflect.DeepEqual(got, want) {
					t.Errorf("repeat %s got %#v want %#v", binding.Key, got, want)
				}
				return nil
			}}
			if code := parseDispatchCLI(args, env, cli.IO{Out: &out, Err: &out}); code != 0 || calls != 1 {
				t.Fatalf("repeat %s code=%d calls=%d %s", binding.Key, code, calls, &out)
			}
		}
	}
	cases := []struct {
		args             []string
		code             int
		item, repo, mode string
	}{
		{[]string{"issue-7", "--repo=first", "--repo", "last"}, 0, "issue-7", "last", ""},
		{[]string{"--repo", "global", "issue-7"}, 0, "issue-7", "global", ""},
		{[]string{"--", "-item"}, 0, "-item", "", ""},
		{[]string{"--trace", "--stamp-only", "--repo", "example/repo"}, 0, "", "example/repo", "--stamp-only"},
		{[]string{"--trace=false", "--stamp-only", "--repo", "example/repo"}, 0, "", "example/repo", "--stamp-only"},
		{[]string{"-trace=true", "--stamp-only", "--repo", "example/repo"}, 0, "", "example/repo", "--stamp-only"},
		{[]string{"--trace=bad", "--stamp-only"}, 2, "", "", ""},
		{[]string{"--stamp-only", "--repo", "example/repo", "--trace"}, 0, "", "example/repo", "--stamp-only"},
		{[]string{"issue-7", "--trace", "--repo=-trace"}, 0, "issue-7", "-trace", ""},
		{[]string{"issue-7", "--no-such-flag"}, 2, "", "", ""},
		{[]string{"issue-7", "--pr=bad"}, 2, "", "", ""},
		{[]string{"issue-7", "--dry-run=bad"}, 2, "", "", ""},
		{[]string{"issue-7", "--repo"}, 2, "", "", ""},
		{[]string{"issue-7", "extra"}, 2, "", "", ""},
		{[]string{"issue-7", "--", "--dry-run"}, 2, "", "", ""},
		{[]string{"--stamp-only", "--branch=x"}, 2, "", "", ""},
		{[]string{"--check-verifier", "--tier=strong"}, 2, "", "", ""},
		{[]string{"--attest-verifier", "extra"}, 2, "", "", ""},
		{[]string{"__complete"}, 2, "", "", ""},
		{[]string{"__completeNoDesc"}, 2, "", "", ""},
	}
	for _, c := range cases {
		t.Run(strings.Join(c.args, "_"), func(t *testing.T) {
			defer deskkit.ResetTrace()
			calls, reads := 0, 0
			env := dispatchCLI{before: func() error { reads++; return nil }, handle: func(mode string, o dispatchOpts, _ string) error {
				calls++
				if o.item != c.item || o.repo != c.repo || mode != c.mode {
					t.Errorf("mode=%q item=%q repo=%q", mode, o.item, o.repo)
				}
				return nil
			}}
			var out bytes.Buffer
			code := parseDispatchCLI(c.args, env, cli.IO{Out: &out, Err: &out})
			if code != c.code {
				t.Fatalf("code %d want %d: %s", code, c.code, &out)
			}
			if c.code == 0 && calls != 1 {
				t.Errorf("handler calls %d", calls)
			}
			if c.code != 0 && (calls != 0 || reads != 0) {
				t.Errorf("parse failure ran handler/config: %d/%d", calls, reads)
			}
			if c.code == 2 && strings.Count(out.String(), "Run 'deskdispatch --help'") != 1 {
				t.Errorf("usage error not printed once: %s", &out)
			}
		})
	}
	// A domain error keeps its own code and is reported once by the shared exit path.
	for _, code := range []int{3, 4, 5, 6} {
		var out bytes.Buffer
		env := dispatchCLI{handle: func(string, dispatchOpts, string) error {
			return &deskkit.DeskError{Code: code, Msg: "domain sentinel"}
		}}
		if got := parseDispatchCLI([]string{"issue-7"}, env, cli.IO{Out: &out, Err: &out}); got != code || strings.Count(out.String(), "domain sentinel") != 1 {
			t.Errorf("domain code=%d got=%d: %s", code, got, &out)
		}
	}
}

// cliDefault is the pre-port matrix, independent of production declarations.
func cliDefault(mode, key string) any {
	switch key {
	case "pr", "attestation":
		return 0
	case "gate-human", "quiet", "dry-run", "rework", "attest-worker", "cross-repo":
		return false
	case "tier":
		if mode == "" {
			return "any"
		}
		return ""
	case "kit":
		return "worker"
	case "root":
		if mode == "" {
			return "."
		}
		return ""
	default:
		return ""
	}
}
