// cliDefault is the pre-port matrix, independent of production declarations.
func cliDefault(mode, key string) any {
	switch key {
	case "pr", "attestation":
		return 0
	case "gate-human", "quiet", "dry-run", "rework", "attest-worker", "cross-repo":
		return false
	case "tier":
		if mode == "" {
			return "any"
		}
		return ""
	case "kit":
		return "worker"
	case "root":
		if mode == "" {
			return "."
		}
		return ""
	default:
		return ""
	}
}

// cliHomeStamp observes silent opt-in telemetry writes as well as config/cache state.
func cliHomeStamp(t *testing.T, root string) map[string]string {
	t.Helper()
	files := map[string]string{}
	err := filepath.WalkDir(root, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		if d.IsDir() {
			files[rel] = "directory"
			return nil
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		files[rel] = string(data)
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	return files
}
