func cliBuildBinary(t *testing.T) string {
	t.Helper()
	bin := filepath.Join(t.TempDir(), "deskwt")
	if runtime.GOOS == "windows" {
		bin += ".exe"
	}
	if out, err := goquiet.Cmd(exec.Command("go", "build", "-o", bin, ".")).CombinedOutput(); err != nil {
		t.Fatalf("build: %v\n%s", err, out)
	}
	return bin
}

// cliHome is a fresh home whose roster.env holds one malformed configuration.
func cliHome(t *testing.T, content string, write bool) string {
	t.Helper()
	home := t.TempDir()
	dir := filepath.Join(home, ".config", "assay")
	if err := os.MkdirAll(dir, 0o700); err != nil {
		t.Fatal(err)
	}
	if write {
		if err := os.WriteFile(filepath.Join(dir, "roster.env"), []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return home
}

// cliChildEnv is a hermetic environment: malformed values everywhere a loader would look,
// the kill switch armed, and a PATH whose every tool records its own start.
func cliChildEnv(home, consent string) []string {
	env := []string{"HOME=" + home, "USERPROFILE=" + home, "PATH=" + filepath.Join(filepath.Dir(home), "shims"),
		"KUBECONFIG=/dev/null", "DESK_TOOLS_DISABLED=1", "ASSAY_CONFIG_ECHO=full", "DESK_MIN_FREE_BYTES=invalid",
		"CELLS_ROOT=" + filepath.Join(home, "no-cells"), "CELL_GO_CACHE_ROOT=" + filepath.Join(home, "unreadable-cache"),
		"CLI_SHIM_MARK=" + filepath.Join(filepath.Dir(home), "child-started")}
	if consent != "" {
		env = append(env, "ASSAY_TELEMETRY="+consent)
	}
	return env
}

// cliRunHelp runs one help/version form in a scratch directory holding a Git repository and
// requires zero effects: no stderr, no child process, no lock, stamp or configuration
// written — except, under explicit telemetry consent, the one local perf record.
func cliRunHelp(t *testing.T, bin, home string, args []string, consent string) {
	t.Helper()
	shims := filepath.Join(filepath.Dir(home), "shims")
	if err := os.MkdirAll(shims, 0o755); err != nil {
		t.Fatal(err)
	}
	if runtime.GOOS != "windows" {
		for _, name := range []string{"git", "gh", "go", "deskclaim-ref", "desktoken", "kubectl", "ssh", "bash"} {
			shim := "#!/bin/sh\necho \"$0\" >> \"$CLI_SHIM_MARK\"\nexit 1\n"
			if err := os.WriteFile(filepath.Join(shims, name), []byte(shim), 0o755); err != nil {
				t.Fatal(err)
			}
		}
	}
	// A working directory that looks like a repository: a help form that resolved the
	// common Git directory and took a maintenance or singleton lock would write here.
	dir := filepath.Join(filepath.Dir(home), "repo")
	if err := os.MkdirAll(filepath.Join(dir, ".git"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, ".git", "HEAD"), []byte("ref: refs/heads/main\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	mark := filepath.Join(filepath.Dir(home), "child-started")
	ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
	defer cancel()
	cmd := exec.CommandContext(ctx, bin, args...)
	cmd.Dir, cmd.Env = dir, cliChildEnv(home, consent)
	before, beforeRepo := cliTreeStamp(t, home), cliTreeStamp(t, dir)
	var out, errs bytes.Buffer
	cmd.Stdout, cmd.Stderr = &out, &errs
	if err := cmd.Run(); err != nil {
		t.Fatalf("help/version %v consent=%q: %v\n%s\n%s", args, consent, err, &out, &errs)
	}
	if out.Len() == 0 {
		t.Errorf("missing generated help/version output: %v", args)
	}
	if errs.Len() != 0 {
		t.Errorf("help %v read config or ran activation: %s", args, &errs)
	}
	if started, err := os.ReadFile(mark); err == nil {
		t.Errorf("help %v started a child process: %s", args, started)
	}
	if after := cliTreeStamp(t, dir); !reflect.DeepEqual(beforeRepo, after) {
		t.Errorf("help %v wrote into the repository (lock or stamp)", args)
	}
	after := cliTreeStamp(t, home)
	perf := filepath.Join(".config", "assay", "perf")
	var records []string
	perfEntries := 0
	for path, data := range after {
		if path == perf || strings.HasPrefix(path, perf+string(filepath.Separator)) {
			perfEntries++
			if strings.HasSuffix(path, ".jsonl") {
				records = append(records, strings.Split(strings.TrimSpace(data), "\n")...)
			}
			delete(after, path)
		}
	}
	if !reflect.DeepEqual(before, after) {
		t.Errorf("help/version %v consent=%q wrote configuration, lock, audit or cache state", args, consent)
	}
	if consent == "" {
		if perfEntries != 0 {
			t.Errorf("help/version %v wrote telemetry without consent", args)
		}
		return
	}
	want := "other"
	for _, v := range perfVerbs {
		if v == args[0] {
			want = v
		}
	}
	if len(records) != 1 {
		t.Fatalf("consented help %v: %d perf records, want exactly one", args, len(records))
	}
	var rec struct {
		Schema, Tool, Verb string
		Exit               int
		Counters           map[string]int64
		Unavailable        []string
	}
	if err := json.Unmarshal([]byte(records[0]), &rec); err != nil {
		t.Fatal(err)
	}
	if rec.Schema != "perf-v2" || rec.Tool != "deskwt" || rec.Verb != want || rec.Exit != 0 {
		t.Errorf("consented help %v record = %+v, want perf-v2 verb %q exit 0", args, rec, want)
	}
	for _, key := range []string{"subprocess", "http"} {
		n, ok := rec.Counters[key]
		if !ok || n != 0 || slices.Contains(rec.Unavailable, key) {
			t.Errorf("consented help %v counter %q = %d present=%v unavailable=%v, want measured zero", args, key, n, ok, rec.Unavailable)
		}
	}
}

// cliTreeStamp observes every file and directory under root.
func cliTreeStamp(t *testing.T, root string) map[string]string {
	t.Helper()
	files := map[string]string{}
	err := filepath.WalkDir(root, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		if d.IsDir() {
			files[rel] = "directory"
			return nil
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		files[rel] = string(data)
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	return files
}

// cliDefault is the pre-port flag matrix (baseline FlagSets of every verb), independent
// of the production declarations.
func cliDefault(path, key string) any {
	switch path + "/" + key {
	case "add/base":
		return "origin/main"
	case "prune/lock-ttl":
		return "0"
	case "prune/singleton-ttl":
		return "10m0s"
	case "maintain/min-interval":
		return 6 * time.Hour
	case "maintain/timeout":
		return 30 * time.Second
	case "maintain objects/min-interval":
		return 24 * time.Hour
	case "maintain objects/timeout":
		return 2 * time.Minute
	}
	switch key {
	case "detach", "dry-run", "reclaim-stale-locks", "reap-dead-sessions", "no-singleton", "no-branches",
		"branches-only", "no-maintenance", "no-cache", "apply", "json", "no-fetch":
		return false
	}
	return ""
}

// cliFields is every typed option of one parsed call, by binding key.
func cliFields(c wtCall) map[string]any {
	switch c.verb {
	case "add":
		o := c.add
		return map[string]any{"branch": o.branch, "detach": o.detach, "base": o.base, "upstream": o.upstream, "role": o.role,
			"dry-run": o.dryRun, "lock-session": o.lockSession, "adopt-run": o.adoptRun}
	case "remove":
		return map[string]any{"dry-run": c.remove.dryRun}
	case "prune":
		f := c.prune
		return map[string]any{"repo": f.repo, "interval": f.interval, "reclaim-stale-locks": f.reclaim, "lock-ttl": f.lockTTL,
			"reap-dead-sessions": f.reapDead, "dry-run": f.dryRun, "singleton-ttl": f.singletonTTL, "no-singleton": f.noSingleton,
			"no-branches": f.noBranches, "branches-only": f.branchesOnly, "no-maintenance": f.noMaintenance, "no-cache": f.noCache,
			"cells-root": f.cellsRoot, "min-idle": f.minIdle}
	case "maintain":
		o := c.maintain
		return map[string]any{"repo": o.repo, "apply": o.apply, "min-interval": o.interval, "timeout": o.timeout}
	case "objects":
		o := c.objects
		return map[string]any{"repo": o.repo, "apply": o.apply, "dry-run": o.dryRun, "json": o.json, "min-interval": o.interval, "timeout": o.timeout}
	case "role-init", "role-clean":
		f := c.role
		return map[string]any{"role": f.role, "session": f.session, "repo-root": f.repoRoot, "no-fetch": f.noFetch}
	}
	return nil
}

func cliVerbOf(path string) string {
	if path == "maintain objects" {
		return "objects"
	}
	return path
}

// TestCLIConfigFlow proves every setting comes only from its declared flag or its baseline
// default: no environment variable or config key reaches any of them, and a config entry
// naming a declared key is refused rather than admitted.
//
// regression: #2111
func TestCLIConfigFlow(t *testing.T) {
	bindings := wtBindings()
	if len(bindings) != len(cliPaths)+1 {
		t.Fatalf("declared command paths %d, want %d (root + %d verbs)", len(bindings), len(cliPaths)+1, len(cliPaths))
	}
	for _, p := range cliPaths {
		declared := bindings[p.path]
		if len(declared) == 0 {
			t.Fatalf("%s declares no bindings", p.path)
		}
		var keys []string
		for _, b := range declared {
			keys = append(keys, b.Key)
			if len(b.Env) != 0 || b.Config {
				t.Errorf("%s/%s declares an env or config source; deskwt settings are flags only", p.path, b.Key)
			}
		}
		sort.Strings(keys)
		for _, b := range declared {
			t.Run(p.path+"/"+b.Key, func(t *testing.T) {
				if want := cliDefault(p.path, b.Key); !reflect.DeepEqual(b.Default, want) {
					t.Fatalf("declaration default for %s = %#v, baseline %#v", b.Key, b.Default, want)
				}
				for _, row := range clicontract.Precedence {
					args := append([]string{}, p.words...)
					cfg := map[string]any{"unrelated": "ignored"}
					if row.Config != nil {
						cfg["unrelated"] = *row.Config
					}
					lookups := 0
					env := wtCLI{inputs: cli.Inputs{Config: cfg, LookupEnv: func(string) (string, bool) {
						lookups++
						if row.Env != nil {
							return *row.Env, true
						}
						return "", false
					}}}
					want := cliDefault(p.path, b.Key)
					if row.Flag != nil {
						val := *row.Flag
						switch b.Kind {
						case cli.Bool:
							val, want = "true", true
						case cli.Duration:
							val, want = "90m", 90*time.Minute
						default:
							want = val
						}
						args = append(args, "--"+b.Flag+"="+val)
					}
					called := 0
					env.handle = func(c wtCall) error {
						called++
						if c.verb != cliVerbOf(p.path) {
							t.Errorf("verb=%q", c.verb)
						}
						if got := cliFields(c)[b.Key]; !reflect.DeepEqual(got, want) {
							t.Errorf("%s: %s got %#v want %#v", row.Name, b.Key, got, want)
						}
						return nil
					}
					var out bytes.Buffer
					if code := parseWT(args, env, cli.IO{Out: &out, Err: &out}); code != 0 {
						t.Fatalf("%s code=%d: %s", row.Name, code, &out)
					}
					if called != 1 || lookups != 0 {
						t.Fatalf("handoffs=%d undeclared env reads=%d", called, lookups)
					}
				}
				// A declared key is never silently admitted from a config map either.
				called := false
				env := wtCLI{inputs: cli.Inputs{Config: map[string]any{b.Key: b.Default}}, handle: func(wtCall) error { called = true; return nil }}
				var out bytes.Buffer
				if code := parseWT(p.words, env, cli.IO{Out: &out, Err: &out}); code != deskkit.ExitRefused || called {
					t.Fatalf("config binding widened: code=%d called=%v %s", code, called, &out)
				}
			})
		}
		// Every typed field the handler reads is a declared key, and every declared key
		// reaches a typed field: nothing is read that the declaration does not name.
		var out bytes.Buffer
		var fields []string
		env := wtCLI{handle: func(c wtCall) error {
			for k := range cliFields(c) {
				fields = append(fields, k)
			}
			return nil
		}}
		if code := parseWT(p.words, env, cli.IO{Out: &out, Err: &out}); code != 0 {
			t.Fatalf("%s: code %d %s", p.path, code, &out)
		}
		sort.Strings(fields)
		if !reflect.DeepEqual(fields, keys) {
			t.Errorf("%s: handler fields %v, declared keys %v", p.path, fields, keys)
		}
	}
}

// TestCLILegacyForms proves every spelling the pre-port parsers and their callers use still
// reaches the same typed value, and that a malformed line fails before any effect.
//
// regression: #2111
func TestCLILegacyForms(t *testing.T) {
	bindings := wtBindings()
	for _, p := range cliPaths {
		for _, b := range bindings[p.path] {
			if b.Kind != cli.String {
				continue
			}
			for _, path := range clicontract.PathValues {
				for _, form := range clicontract.OptionForms {
					t.Run(p.path+"/"+b.Key+"/"+path.Name+"/"+form.Name, func(t *testing.T) {
						args := append(append([]string{}, p.words...), form.Args(b.Flag, path.Value)...)
						called := 0
						env := wtCLI{handle: func(c wtCall) error {
							called++
							if got := cliFields(c)[b.Key]; got != path.Value {
								t.Errorf("value changed for %s: %#v", b.Key, got)
							}
							return nil
						}}
						var out bytes.Buffer
						if code := parseWT(args, env, cli.IO{Out: &out, Err: &out}); code != 0 || called != 1 {
							t.Fatalf("code=%d calls=%d: %s", code, called, &out)
						}
					})
				}
			}
		}
		// A repeated flag keeps the last value, across the two spellings, as Go's flag did.
		for _, b := range bindings[p.path] {
			first, last := "first", "last"
			var want any = last
			switch b.Kind {
			case cli.Bool:
				first, last, want = "true", "false", false
			case cli.Duration:
				first, last, want = "2h", "3h", 3*time.Hour
			}
			args := append(append([]string{}, p.words...), "--"+b.Flag+"="+first, "-"+b.Flag+"="+last)
			calls := 0
			env := wtCLI{handle: func(c wtCall) error {
				calls++
				if got := cliFields(c)[b.Key]; !reflect.DeepEqual(got, want) {
					t.Errorf("repeat %s/%s got %#v want %#v", p.path, b.Key, got, want)
				}
				return nil
			}}
			var out bytes.Buffer
			if code := parseWT(args, env, cli.IO{Out: &out, Err: &out}); code != 0 || calls != 1 {
				t.Fatalf("repeat %s/%s code=%d calls=%d %s", p.path, b.Key, code, calls, &out)
			}
		}
	}

	// The callers' own lines (dispatch homes, boot, the cell launcher) and the interspersed
	// positions the pre-port parser accepted.
	type want struct {
		verb   string
		fields map[string]any
		name   string // add name, remove path, or role positionals joined
	}
	cases := []struct {
		args []string
		code int
		want want
	}{
		{[]string{"add", "wt-1", "--branch", "b1", "--base", "origin/main", "--role", "worker"}, 0,
			want{"add", map[string]any{"branch": "b1", "base": "origin/main", "role": "worker"}, "wt-1"}},
		{[]string{"add", "--branch", "b1", "wt-1", "--dry-run"}, 0, want{"add", map[string]any{"branch": "b1", "dry-run": true}, "wt-1"}},
		{[]string{"add", "wt-1", "--detach", "--base", "0123abc", "--role", "verifier"}, 0,
			want{"add", map[string]any{"detach": true, "base": "0123abc"}, "wt-1"}},
		{[]string{"add", "wt-1", "--branch", "b1", "--upstream", "refs/remotes/origin/b1", "--adopt-run", "run-7", "--base", "0123abc", "--role", "worker"}, 0,
			want{"add", map[string]any{"upstream": "refs/remotes/origin/b1", "adopt-run": "run-7"}, "wt-1"}},
		{[]string{"add", "wt-1", "--lock-session", "s-1"}, 0, want{"add", map[string]any{"lock-session": "s-1"}, "wt-1"}},
		{[]string{"add", "-branch=b1", "wt-1"}, 0, want{"add", map[string]any{"branch": "b1"}, "wt-1"}},
		{[]string{"add", "--", "-dashed"}, 0, want{"add", map[string]any{}, "-dashed"}},
		{[]string{"--trace", "add", "wt-1"}, 0, want{"add", map[string]any{}, "wt-1"}},
		{[]string{"add", "wt-1", "--trace"}, 0, want{"add", map[string]any{}, "wt-1"}},
		{[]string{"remove", "/tmp/wt-1"}, 0, want{"remove", map[string]any{"dry-run": false}, "/tmp/wt-1"}},
		{[]string{"remove", "--dry-run", "/tmp/wt-1"}, 0, want{"remove", map[string]any{"dry-run": true}, "/tmp/wt-1"}},
		{[]string{"prune", "--repo", "/r"}, 0, want{"prune", map[string]any{"repo": "/r", "lock-ttl": "0", "singleton-ttl": "10m0s"}, ""}},
		{[]string{"prune", "-repo", "/r", "-reap-dead-sessions", "-lock-ttl", "24h"}, 0,
			want{"prune", map[string]any{"repo": "/r", "reap-dead-sessions": true, "lock-ttl": "24h"}, ""}},
		{[]string{"prune", "--interval", "30m", "--reclaim-stale-locks"}, 0,
			want{"prune", map[string]any{"interval": "30m", "reclaim-stale-locks": true}, ""}},
		{[]string{"prune", "--branches-only", "--no-singleton"}, 0, want{"prune", map[string]any{"branches-only": true, "no-singleton": true}, ""}},
		{[]string{"maintain", "--repo", "/r", "--apply", "--min-interval", "12h", "--timeout", "1m"}, 0,
			want{"maintain", map[string]any{"repo": "/r", "apply": true, "min-interval": 12 * time.Hour, "timeout": time.Minute}, ""}},
		{[]string{"maintain"}, 0, want{"maintain", map[string]any{"apply": false}, ""}},
		{[]string{"maintain", "objects", "--json", "--dry-run"}, 0, want{"objects", map[string]any{"json": true, "dry-run": true, "apply": false}, ""}},
		{[]string{"maintain", "objects", "--apply", "--min-interval", "48h"}, 0,
			want{"objects", map[string]any{"apply": true, "min-interval": 48 * time.Hour}, ""}},
		// The global --trace (and the root's other persistent flags) may sit between
		// `maintain` and `objects`: the pre-port parser stripped --trace wherever it was.
		{[]string{"maintain", "--trace", "objects"}, 0, want{"objects", map[string]any{"apply": false}, ""}},
		{[]string{"maintain", "-trace", "objects", "--apply"}, 0, want{"objects", map[string]any{"apply": true}, ""}},
		{[]string{"maintain", "--trace=false", "objects", "--json"}, 0, want{"objects", map[string]any{"json": true}, ""}},
		{[]string{"maintain", "--perf-role", "worker", "objects"}, 0, want{"objects", map[string]any{"apply": false}, ""}},
		// A verb flag there is still a refusal, with or without a --trace beside it.
		{[]string{"maintain", "--trace", "--apply", "objects"}, 2, want{}},
		{[]string{"-trace", "maintain", "-apply", "objects"}, 2, want{}},
		{[]string{"role-init", "worker", "--session", "s-1"}, 0, want{"role-init", map[string]any{"session": "s-1"}, "worker"}},
		{[]string{"role-init", "--role", "worker", "--no-fetch"}, 0, want{"role-init", map[string]any{"role": "worker", "no-fetch": true}, ""}},
		{[]string{"role-clean", "--session", "s-1", "worker"}, 0, want{"role-clean", map[string]any{"session": "s-1"}, "worker"}},
		// Malformed lines: the usage code, nothing read, nothing run.
		{[]string{"add"}, 2, want{}},
		{[]string{"add", "a", "b"}, 2, want{}},
		{[]string{"add", "a", "--no-such-flag"}, 2, want{}},
		{[]string{"add", "a", "--detach=maybe"}, 2, want{}},
		{[]string{"add", "a", "--branch"}, 2, want{}},
		{[]string{"remove"}, 2, want{}},
		{[]string{"remove", "--force", "/tmp/x"}, 2, want{}},
		{[]string{"prune", "stray"}, 2, want{}},
		{[]string{"prune", "--dry-run=bad"}, 2, want{}},
		{[]string{"maintain", "--timeout", "bogus"}, 2, want{}},
		{[]string{"maintain", "--apply", "objects"}, 2, want{}},
		{[]string{"maintain", "gc"}, 2, want{}},
		{[]string{"maintain", "objects", "--prefetch"}, 2, want{}},
		{[]string{"maintain", "objects", "--min-interval", "soon"}, 2, want{}},
		{[]string{"role-init", "a", "b"}, 2, want{}},
		{[]string{"frobnicate"}, 2, want{}},
		{[]string{"--trace=bad", "prune"}, 2, want{}},
		{[]string{"__complete"}, 2, want{}},
		{[]string{"__completeNoDesc"}, 2, want{}},
		// No verb at all is the refusal it always was.
		{nil, deskkit.ExitRefused, want{}},
	}
	for _, c := range cases {
		t.Run(strings.Join(c.args, "_"), func(t *testing.T) {
			defer deskkit.ResetTrace()
			calls, reads := 0, 0
			env := wtCLI{before: func() error { reads++; return nil }, handle: func(got wtCall) error {
				calls++
				if got.verb != c.want.verb {
					t.Errorf("verb %q want %q", got.verb, c.want.verb)
				}
				fields := cliFields(got)
				for k, v := range c.want.fields {
					if !reflect.DeepEqual(fields[k], v) {
						t.Errorf("%s = %#v want %#v", k, fields[k], v)
					}
				}
				name := strings.Join(got.role.positionals, " ")
				switch got.verb {
				case "add":
					name = got.add.name
				case "remove":
					name = got.remove.path
				}
				if name != c.want.name {
					t.Errorf("positional %q want %q", name, c.want.name)
				}
				return nil
			}}
			var out bytes.Buffer
			code := parseWT(c.args, env, cli.IO{Out: &out, Err: &out})
			if code != c.code {
				t.Fatalf("code %d want %d: %s", code, c.code, &out)
			}
			if c.code == 0 && (calls != 1 || reads != 1) {
				t.Errorf("handler calls %d, config reads %d, want 1/1", calls, reads)
			}
			if c.code != 0 && (calls != 0 || reads != 0) {
				t.Errorf("parse failure ran handler/config: %d/%d", calls, reads)
			}
			if c.code == 2 && strings.Count(out.String(), "Run 'deskwt --help'") != 1 {
				t.Errorf("usage error not printed once: %s", &out)
			}
		})
	}
	// --version takes no words. The pre-port parser answered it only as the sole argument and
	// refused anything beside it as an unknown verb; that is the usage code now, with nothing
	// printed on stdout. With only --trace beside it, it still prints the version.
	for _, c := range []struct {
		args []string
		code int
	}{
		{[]string{"--version", "extra"}, 2},
		{[]string{"extra", "--version"}, 2},
		{[]string{"-version", "add", "x"}, 2},
		{[]string{"add", "x", "--version"}, 2},
		{[]string{"--version"}, 0},
		{[]string{"-version"}, 0},
		{[]string{"--trace", "--version"}, 0},
		{[]string{"--version", "--trace"}, 0},
	} {
		t.Run("version_"+strings.Join(c.args, "_"), func(t *testing.T) {
			defer deskkit.ResetTrace()
			calls := 0
			env := wtCLI{before: func() error { calls++; return nil }, handle: func(wtCall) error { calls++; return nil }}
			var out, errs bytes.Buffer
			code := parseWT(c.args, env, cli.IO{Out: &out, Err: &errs})
			if code != c.code || calls != 0 {
				t.Fatalf("code %d calls %d, want %d/0: %s%s", code, calls, c.code, &out, &errs)
			}
			printed := strings.HasPrefix(out.String(), "deskwt sourceSHA=")
			if printed != (c.code == 0) {
				t.Errorf("version printed=%v for code %d: stdout %q", printed, code, &out)
			}
			if c.code == 2 && strings.Count(errs.String(), "Run 'deskwt --help'") != 1 {
				t.Errorf("usage error not printed once: %s", &errs)
			}
		})
	}

	// A domain error keeps its own code and is reported once by the shared exit path.
	for _, code := range []int{3, 4, 5, 6} {
		var out bytes.Buffer
		env := wtCLI{handle: func(wtCall) error { return &deskkit.DeskError{Code: code, Msg: "domain sentinel"} }}
		if got := parseWT([]string{"prune"}, env, cli.IO{Out: &out, Err: &out}); got != code || strings.Count(out.String(), "domain sentinel") != 1 {
			t.Errorf("domain code=%d got=%d: %s", code, got, &out)
		}
	}
}

// TestCLILifecycleParity drives the real handlers through the tree: the maintenance
// opt-in, its lock custody, invalid bounds and combinations, and the prune loop's
// singleton release keep their pre-port behaviour, and no parse failure takes a lock.
//
// regression: #2111
func TestCLILifecycleParity(t *testing.T) {
	gitDirNames := func(t *testing.T, work string) []string {
		t.Helper()
		ents, err := os.ReadDir(filepath.Join(work, ".git"))
		if err != nil {
			t.Fatal(err)
		}
		var names []string
		for _, e := range ents {
			names = append(names, e.Name())
		}
		return names
	}

	t.Run("plain maintain is read-only and only --apply writes", func(t *testing.T) {
		work, calls := maintenanceFixture(t)
		plan, err := maintenanceRun(t, "--repo", work)
		if err != nil || plan.Status != "plan" || maintenanceWrites(*calls) != 0 {
			t.Fatalf("plan wrote or failed: %+v %v %v", plan, err, *calls)
		}
		if _, err := os.Stat(filepath.Join(work, ".git", "assay-maintenance.lock")); !os.IsNotExist(err) {
			t.Fatalf("the read-only plan took the maintenance lock: %v", err)
		}
		applied, err := maintenanceRun(t, "--repo", work, "--apply")
		if err != nil || applied.Status == "plan" || maintenanceWrites(*calls) == 0 {
			t.Fatalf("--apply did not apply: %+v %v", applied, err)
		}
	})

	t.Run("held maintenance lock reports held", func(t *testing.T) {
		work, calls := maintenanceFixture(t)
		f, err := os.OpenFile(filepath.Join(work, ".git", "assay-maintenance.lock"), os.O_RDWR|os.O_CREATE, 0o600)
		if err != nil {
			t.Fatal(err)
		}
		defer f.Close()
		if err := deskkit.TryLockExclusive(f); err != nil {
			t.Fatal(err)
		}
		defer deskkit.UnlockFile(f)
		held, err := maintenanceRun(t, "--repo", work, "--apply")
		if err != nil || held.Status != "held" || maintenanceWrites(*calls) != 0 {
			t.Fatalf("a held lock was not respected: %+v %v", held, err)
		}
	})

	t.Run("nested help and malformed lines take no lock and run nothing", func(t *testing.T) {
		work, mcalls := maintenanceFixture(t)
		for _, c := range []struct {
			args []string
			code int
		}{
			{[]string{"maintain", "objects", "--help"}, 0},
			{[]string{"maintain", "--apply", "--help"}, 0},
			{[]string{"maintain", "--repo", work, "--apply", "--timeout", "bogus"}, 2},
			{[]string{"maintain", "--repo", work, "--apply", "objects"}, 2},
			{[]string{"maintain", "objects", "--repo", work, "--apply", "--min-interval", "soon"}, 2},
			{[]string{"prune", "--repo", work, "--reap-dead-sessions", "stray"}, 2},
			// Domain bounds and combinations: refused before any lock or Git command.
			{[]string{"maintain", "--repo", work, "--apply", "--min-interval", "30m"}, deskkit.ExitRefused},
			{[]string{"maintain", "--repo", work, "--apply", "--timeout", "10m"}, deskkit.ExitRefused},
			{[]string{"maintain", "objects", "--repo", work, "--apply", "--dry-run"}, deskkit.ExitRefused},
			{[]string{"prune", "--repo", work, "--interval", "30m", "--dry-run"}, deskkit.ExitRefused},
			{[]string{"prune", "--repo", work, "--reclaim-stale-locks", "--reap-dead-sessions"}, deskkit.ExitRefused},
			{[]string{"prune", "--repo", work, "--lock-ttl", "24h"}, deskkit.ExitRefused},
			{[]string{"prune", "--repo", work, "--interval", "soon"}, deskkit.ExitRefused},
		} {
			before := gitDirNames(t, work)
			n := len(*mcalls)
			rc, _, stderr := runCapBoth(t, c.args)
			if rc != c.code {
				t.Fatalf("%v: rc %d want %d\n%s", c.args, rc, c.code, stderr)
			}
			if after := gitDirNames(t, work); !reflect.DeepEqual(before, after) {
				t.Errorf("%v changed the Git directory: %v -> %v", c.args, before, after)
			}
			if len(*mcalls) != n {
				t.Errorf("%v ran a maintenance command: %v", c.args, (*mcalls)[n:])
			}
		}
	})

	t.Run("prune --interval releases the singleton between sweeps", func(t *testing.T) {
		work := newRepo(t)
		withEnv(t, work)
		stamp := stampPathFor(t, work)
		var rc int
		done := make(chan struct{})
		freed := false
		_ = runCapOut(t, func() {
			go func() {
				defer close(done)
				rc, _ = runCapErr(t, []string{"prune", "--repo", work, "--interval", "50ms", "--singleton-ttl", "0", "--no-maintenance", "--no-cache"})
			}()
			deadline := time.Now().Add(10 * time.Second)
			for time.Now().Before(deadline) && !freed {
				if fi, err := os.Stat(stamp); err == nil && fi.Size() > 0 {
					if f, err := os.OpenFile(stamp, os.O_RDWR, 0o600); err == nil {
						if deskkit.TryLockExclusive(f) == nil {
							freed = true
							_ = deskkit.UnlockFile(f)
						}
						_ = f.Close()
					}
				}
				time.Sleep(5 * time.Millisecond)
			}
			// The kill switch halts the loop at its next iteration boundary.
			_ = os.Setenv("DESK_TOOLS_DISABLED", "1")
			<-done
		})
		if !freed {
			t.Fatalf("the interval loop never released the singleton between sweeps")
		}
		if rc != deskkit.ExitDisabled {
			t.Fatalf("the loop did not halt on the kill switch: rc %d", rc)
		}
	})
}
